-- Canvas Angular: bảng hiện tại giữ bản nháp đang chỉnh sửa.
CREATE TABLE SJAVAJRXMLTEMPLATE (
    ID VARCHAR(36) NOT NULL,
    STEMPLATEID VARCHAR(36) NOT NULL,
    NAME VARCHAR(255) NOT NULL,
    JRXML BLOB SUB_TYPE TEXT CHARACTER SET UTF8,
    STATUS INTEGER DEFAULT 10 NOT NULL,
    VERSIONNO INTEGER DEFAULT 1 NOT NULL,
    TIMECREATED TIMESTAMP,
    TIMEMODIFIED TIMESTAMP,
    CONSTRAINT PK_SJAVAJRXMLTEMPLATE PRIMARY KEY (ID)
);

CREATE UNIQUE INDEX UQ_SJJT_STEMPLATE ON SJAVAJRXMLTEMPLATE (STEMPLATEID);

-- Mỗi lần xuất bản tạo một snapshot bất biến; luồng in chỉ đọc bảng này.
CREATE TABLE SJAVAJRXMLVERSION (
    ID VARCHAR(36) NOT NULL,
    STEMPLATEID VARCHAR(36) NOT NULL,
    VERSIONNO INTEGER NOT NULL,
    NAME VARCHAR(255) NOT NULL,
    JRXML BLOB SUB_TYPE TEXT CHARACTER SET UTF8,
    STATUS INTEGER DEFAULT 30 NOT NULL,
    PUBLISHEDAT TIMESTAMP,
    PUBLISHEDBY VARCHAR(36),
    CONSTRAINT PK_SJAVAJRXMLVERSION PRIMARY KEY (ID)
);

CREATE UNIQUE INDEX UQ_SJJV_TEMPLATE_VER ON SJAVAJRXMLVERSION (STEMPLATEID, VERSIONNO);
