package kazuko.ex.model.congno;

public class CongNoKhachHangItem {
    private String khachHangId;
    private String maKhach;
    private String tenKhach;
    private String nhomKhachId;
    private String tenNhomKhach;
    private String diaChi;
    private String dienThoai;
    private String email;
    private String maSoThue;
    private double tongMua;
    private double tongDaTra;
    private double conNo;

    public CongNoKhachHangItem() {}

    public String getKhachHangId() { return khachHangId; }
    public void setKhachHangId(String khachHangId) { this.khachHangId = khachHangId; }

    public String getMaKhach() { return maKhach; }
    public void setMaKhach(String maKhach) { this.maKhach = maKhach; }

    public String getTenKhach() { return tenKhach; }
    public void setTenKhach(String tenKhach) { this.tenKhach = tenKhach; }

    public String getNhomKhachId() { return nhomKhachId; }
    public void setNhomKhachId(String nhomKhachId) { this.nhomKhachId = nhomKhachId; }

    public String getTenNhomKhach() { return tenNhomKhach; }
    public void setTenNhomKhach(String tenNhomKhach) { this.tenNhomKhach = tenNhomKhach; }

    public String getDiaChi() { return diaChi; }
    public void setDiaChi(String diaChi) { this.diaChi = diaChi; }

    public String getDienThoai() { return dienThoai; }
    public void setDienThoai(String dienThoai) { this.dienThoai = dienThoai; }

    public String getEmail() { return email; }
    public void setEmail(String email) { this.email = email; }

    public String getMaSoThue() { return maSoThue; }
    public void setMaSoThue(String maSoThue) { this.maSoThue = maSoThue; }

    public double getTongMua() { return tongMua; }
    public void setTongMua(double tongMua) { this.tongMua = tongMua; }

    public double getTongDaTra() { return tongDaTra; }
    public void setTongDaTra(double tongDaTra) { this.tongDaTra = tongDaTra; }

    public double getConNo() { return conNo; }
    public void setConNo(double conNo) { this.conNo = conNo; }
}
