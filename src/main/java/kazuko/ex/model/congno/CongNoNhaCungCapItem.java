package kazuko.ex.model.congno;

public class CongNoNhaCungCapItem {
    private String nhaCungCapId;
    private String maNCC;
    private String tenNCC;
    private String nhomNCCId;
    private String tenNhomNCC;
    private String diaChi;
    private String dienThoai;
    private String email;
    private double tongNhap;
    private double tongDaTra;
    private double conNo;

    public CongNoNhaCungCapItem() {}

    public String getNhaCungCapId() { return nhaCungCapId; }
    public void setNhaCungCapId(String nhaCungCapId) { this.nhaCungCapId = nhaCungCapId; }

    public String getMaNCC() { return maNCC; }
    public void setMaNCC(String maNCC) { this.maNCC = maNCC; }

    public String getTenNCC() { return tenNCC; }
    public void setTenNCC(String tenNCC) { this.tenNCC = tenNCC; }

    public String getNhomNCCId() { return nhomNCCId; }
    public void setNhomNCCId(String nhomNCCId) { this.nhomNCCId = nhomNCCId; }

    public String getTenNhomNCC() { return tenNhomNCC; }
    public void setTenNhomNCC(String tenNhomNCC) { this.tenNhomNCC = tenNhomNCC; }

    public String getDiaChi() { return diaChi; }
    public void setDiaChi(String diaChi) { this.diaChi = diaChi; }

    public String getDienThoai() { return dienThoai; }
    public void setDienThoai(String dienThoai) { this.dienThoai = dienThoai; }

    public String getEmail() { return email; }
    public void setEmail(String email) { this.email = email; }

    public double getTongNhap() { return tongNhap; }
    public void setTongNhap(double tongNhap) { this.tongNhap = tongNhap; }

    public double getTongDaTra() { return tongDaTra; }
    public void setTongDaTra(double tongDaTra) { this.tongDaTra = tongDaTra; }

    public double getConNo() { return conNo; }
    public void setConNo(double conNo) { this.conNo = conNo; }
}
